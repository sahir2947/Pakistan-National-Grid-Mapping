"""Exports the grid layout and Pakistan's border for the map viewer.

viewer/layout.js holds the row and column counts; viewer/boundary.js holds the
border. The viewer recomputes every edge and border flag from them with the
same formulas as the library, so it needs no database.
"""

import json
from pathlib import Path

from . import __version__, geodesy, spec
from .boundary import Boundary
from .layout import GridLayout

HEADER = "// Generated by `pakgrid export-layout`. Do not edit by hand.\n"


def layout_data(layout=None):
    layout = layout or GridLayout.from_spec()
    return {
        "grid_version": spec.GRID_VERSION,
        "library_version": __version__,
        "datum": spec.DATUM,
        "bounds": {"south": spec.SOUTH, "west": spec.WEST, "north": spec.NORTH, "east": spec.EAST},
        "midlines": {"lat": spec.MID_LAT, "lon": spec.MID_LON},
        "cell_size_m": spec.CELL_SIZE_M,
        "subdivisions": spec.SUBDIVISIONS,
        "area_km2": round(geodesy.rect_area(spec.SOUTH, spec.NORTH, spec.WEST, spec.EAST) / 1e6),
        "total_cells": layout.total_cells,
        "total_sub_cells": layout.total_sub_cells,
        "quadrants": [
            {
                "q": ql.q,
                "code": ql.code,
                "name": ql.name,
                "bounds": {"south": ql.south, "west": ql.west, "north": ql.north, "east": ql.east},
                "area_km2": round(geodesy.rect_area(ql.south, ql.north, ql.west, ql.east) / 1e6),
                "nrows": ql.nrows,
                "ncells": ql.ncells,
                "ncols": list(ql.ncols),
            }
            for ql in layout.quadrants
        ],
    }


def _module_js(global_name, data):
    body = json.dumps(data, separators=(",", ":"), ensure_ascii=False)
    return (HEADER + "(function (root) {\n  var data = " + body + ";\n"
            "  if (typeof module !== \"undefined\" && module.exports) { module.exports = data; }\n"
            f"  else {{ root.{global_name} = data; }}\n}})(this);\n")


def layout_js(layout=None):
    return _module_js("PAKGRID_LAYOUT", layout_data(layout))


def boundary_data(boundary=None):
    """The border with each ring delta-encoded: [lon0, lat0, dlon1, dlat1, ...] in 1e-7 degree."""
    boundary = boundary or Boundary.default()
    rings = []
    for ring in boundary.rings:
        flat, px, py = [], 0, 0
        for x, y in ring:
            flat += (x - px, y - py)
            px, py = x, y
        rings.append(flat)
    return {"name": boundary.name, "license": boundary.license, "attribution": boundary.attribution,
            "sha256": boundary.sha256, "rings": rings}


def boundary_js(boundary=None):
    return _module_js("PAKGRID_BOUNDARY", boundary_data(boundary))


def write_viewer_files(directory):
    """Write layout.js and boundary.js into the viewer directory."""
    directory = Path(directory)
    out = []
    for name, text in (("layout.js", layout_js()), ("boundary.js", boundary_js())):
        (directory / name).write_text(text, encoding="utf-8")
        out.append(directory / name)
    return out
